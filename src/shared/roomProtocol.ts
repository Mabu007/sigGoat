/**
 * TRADINGVIBES ROOM REALTIME PROTOCOL
 * ====================================
 * A single, VERSIONED wire format shared by three runtimes:
 *
 *   - the browser client        (src/lib/roomSocket.ts)
 *   - the Cloudflare Worker     (realtime/src/roomCoordinator.ts)
 *   - the Durable Object        (realtime/src/roomCoordinator.ts)
 *
 * It is deliberately dependency-free (no DOM, no Node, no Workers types) so
 * the same file can be compiled by Vite for the browser and by esbuild/wrangler
 * for the Worker without a shim.
 *
 * DESIGN RULES
 * ------------
 * 1. Everything on the wire is JSON. Binary was rejected: the payloads here
 *    are tiny, and JSON keeps the protocol inspectable in a browser devtools
 *    frame and readable in a Cloudflare log line.
 *
 * 2. `v` is mandatory on every message. A peer that receives an unknown
 *    version is told to resync rather than guessing. Silent version drift is
 *    how "the chart is stuck on the wrong symbol" bugs happen.
 *
 * 3. Transient, high-frequency events (pointer movement while dragging a
 *    drawing) are NEVER sent over this socket. The client renders the drag
 *    locally and only a committed change (create / update / remove) crosses
 *    the wire. This is what keeps the Durable Object — and the durable
 *    Firestore snapshot behind it — from being flooded.
 *
 * 4. The server is authoritative. A client may ASK to change the shared
 *    symbol; the server decides whether that member is allowed to, and
 *    broadcasts the result. Clients never broadcast to each other.
 */

export const ROOM_PROTOCOL_VERSION = 1;

/** Hard ceiling on a single inbound frame. Anything larger is a protocol
 *  error, not a message. Keeps a hostile client from filling Durable Object
 *  memory with one enormous string. */
export const ROOM_MAX_FRAME_BYTES = 64 * 1024;

/** Ceiling on the number of drawings a room may hold. Older drawings are
 *  evicted first. Without this a room could grow without bound. */
export const ROOM_MAX_DRAWINGS = 300;

/** Ceiling on the number of chat-style activity entries retained in the
 *  Durable Object's in-memory ring buffer. */
export const ROOM_MAX_ACTIVITY = 50;

/** How long a signed media upload ticket stays valid. */
export const MEDIA_TICKET_TTL_MS = 10 * 60 * 1000;

/** How long a signed media DELIVERY url stays valid. Delivery urls are
 *  regenerated by the server on every read, so this only needs to outlive a
 *  single page view. */
export const MEDIA_DELIVERY_TTL_MS = 24 * 60 * 60 * 1000;

// ---------------------------------------------------------------------------
// Drawings
// ---------------------------------------------------------------------------

export type DrawingKind = 'trendline' | 'ray' | 'hline' | 'vline' | 'rect';

export interface DrawingPoint {
  /** Epoch seconds. Matches lightweight-charts' `Time` in seconds. */
  time: number;
  price: number;
}

export interface RoomDrawing {
  id: string;
  kind: DrawingKind;
  /** Two points for lines; two corners for a rectangle. */
  points: DrawingPoint[];
  /** CSS colour, e.g. "#79e5c2". */
  color: string;
  /** Stroke width in pixels. */
  width: number;
  /** Author attribution. `createdBy` is the Firebase uid, never trusted. */
  createdBy: string;
  createdByName?: string;
  createdAt: number;
  /** Bumped on every committed change. */
  version: number;
  /** Optional label rendered at the drawing's midpoint. */
  label?: string;
}

// ---------------------------------------------------------------------------
// Presence & voice
// ---------------------------------------------------------------------------

export type RoomRole = 'OWNER' | 'LEADER' | 'MEMBER' | 'GUEST';

export interface RoomParticipant {
  /** Stable per-connection id. */
  id: string;
  /** Firebase uid. Empty for an anonymous visitor. */
  uid: string;
  name: string;
  role: RoomRole;
  /** True while the participant holds a live voice connection. */
  speaking?: boolean;
  muted?: boolean;
  joinedAt: number;
}

export interface VoiceParticipant {
  id: string;
  uid: string;
  name: string;
  muted: boolean;
  speaking: boolean;
  /** SFU session id of the publisher. */
  sessionId?: string;
  trackName?: string;
}

// ---------------------------------------------------------------------------
// Session lifecycle
// ---------------------------------------------------------------------------

export type RoomSessionStatus = 'idle' | 'starting' | 'live' | 'ending' | 'ended';

export interface RoomSessionState {
  id: string;
  roomId: string;
  status: RoomSessionStatus;
  startedAt: number;
  endedAt?: number;
  startedBy: string;
  startedByName?: string;
  /** Shared symbol at session start. */
  symbol?: string;
  timeframe?: string;
  /** True while the room leader is capturing a local recording. */
  recording?: boolean;
  /** Number of connected participants. */
  participantCount?: number;
}

// ---------------------------------------------------------------------------
// Shared room state
// ---------------------------------------------------------------------------

export interface RoomChartState {
  symbol: string;
  timeframe: string;
  drawings: RoomDrawing[];
}

export interface RoomRealtimeState {
  version: number;
  chart: RoomChartState;
  session: RoomSessionState | null;
  participants: RoomParticipant[];
  voice: {
    enabled: boolean;
    participants: VoiceParticipant[];
  };
  /** Server time, so a client can correct clock skew. */
  serverTime: number;
}

// ---------------------------------------------------------------------------
// Messages: client -> server
// ---------------------------------------------------------------------------

export type ClientMessage =
  | { v: number; t: 'hello'; name?: string }
  | { v: number; t: 'state.request' }
  | { v: number; t: 'chart.setSymbol'; symbol: string }
  | { v: number; t: 'chart.setTimeframe'; timeframe: string }
  | { v: number; t: 'drawing.create'; drawing: RoomDrawing }
  | { v: number; t: 'drawing.update'; drawing: RoomDrawing }
  | { v: number; t: 'drawing.remove'; id: string }
  | { v: number; t: 'drawings.clear' }
  | { v: number; t: 'session.start'; symbol?: string; timeframe?: string }
  | { v: number; t: 'session.end' }
  | { v: number; t: 'voice.join' }
  | { v: number; t: 'voice.leave' }
  | { v: number; t: 'voice.mute'; muted: boolean }
  | { v: number; t: 'voice.speaking'; speaking: boolean }
  | { v: number; t: 'ping' };

// ---------------------------------------------------------------------------
// Messages: server -> client
// ---------------------------------------------------------------------------

export type ServerMessage =
  | { v: number; t: 'welcome'; state: RoomRealtimeState; self: RoomParticipant }
  | { v: number; t: 'state'; state: RoomRealtimeState }
  | { v: number; t: 'presence'; participants: RoomParticipant[] }
  | { v: number; t: 'chart.symbol'; symbol: string; by: string; byName?: string }
  | { v: number; t: 'chart.timeframe'; timeframe: string; by: string; byName?: string }
  | { v: number; t: 'drawing.add'; drawing: RoomDrawing }
  | { v: number; t: 'drawing.update'; drawing: RoomDrawing }
  | { v: number; t: 'drawing.remove'; id: string; by: string; byName?: string }
  | { v: number; t: 'drawings.cleared'; by: string; byName?: string }
  | { v: number; t: 'session'; session: RoomSessionState | null }
  | { v: number; t: 'voice'; enabled: boolean; participants: VoiceParticipant[] }
  | { v: number; t: 'error'; code: string; message: string }
  | { v: number; t: 'pong'; serverTime: number };

// ---------------------------------------------------------------------------
// Validation
// ---------------------------------------------------------------------------

export const ALLOWED_TIMEFRAMES = ['1m', '5m', '15m', '1h', '4h', '1D'] as const;
export type Timeframe = (typeof ALLOWED_TIMEFRAMES)[number];

export const ALLOWED_DRAWING_KINDS: DrawingKind[] = [
  'trendline',
  'ray',
  'hline',
  'vline',
  'rect',
];

const SYMBOL_PATTERN = /^[A-Za-z0-9._-]{1,24}$/;
const DRAWING_ID_PATTERN = /^[A-Za-z0-9_-]{1,64}$/;
const COLOR_PATTERN = /^#[0-9a-fA-F]{3,8}$/;

export function isValidSymbol(value: unknown): value is string {
  return typeof value === 'string' && SYMBOL_PATTERN.test(value);
}

export function isValidTimeframe(value: unknown): value is string {
  return (
    typeof value === 'string' &&
    (ALLOWED_TIMEFRAMES as readonly string[]).includes(value)
  );
}

export function isValidDrawingId(value: unknown): value is string {
  return typeof value === 'string' && DRAWING_ID_PATTERN.test(value);
}

function isPoint(value: unknown): value is DrawingPoint {
  if (!value || typeof value !== 'object') return false;
  const point = value as DrawingPoint;
  return (
    Number.isFinite(point.time) &&
    point.time > 0 &&
    Number.isFinite(point.price) &&
    Math.abs(point.price) > 0
  );
}

export function isValidDrawing(value: unknown): value is RoomDrawing {
  if (!value || typeof value !== 'object') return false;
  const drawing = value as RoomDrawing;
  if (!isValidDrawingId(drawing.id)) return false;
  if (!ALLOWED_DRAWING_KINDS.includes(drawing.kind)) return false;
  if (!Array.isArray(drawing.points) || drawing.points.length !== 2) return false;
  if (!drawing.points.every(isPoint)) return false;
  if (typeof drawing.color !== 'string' || !COLOR_PATTERN.test(drawing.color)) {
    return false;
  }
  if (!Number.isFinite(drawing.width) || drawing.width < 0.5 || drawing.width > 8) {
    return false;
  }
  if (typeof drawing.createdBy !== 'string' || drawing.createdBy.length > 128) {
    return false;
  }
  return true;
}

/** Parses and validates an inbound frame. Returns null when the frame is not
 *  a message this protocol understands. Never throws. */
export function parseClientMessage(raw: string): ClientMessage | null {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return null;
  }
  if (!parsed || typeof parsed !== 'object') return null;
  const message = parsed as Record<string, unknown>;
  if (message.v !== ROOM_PROTOCOL_VERSION) return null;
  if (typeof message.t !== 'string') return null;

  switch (message.t) {
    case 'hello':
    case 'state.request':
    case 'drawings.clear':
    case 'session.start':
    case 'session.end':
    case 'voice.join':
    case 'voice.leave':
    case 'ping':
      return { v: message.v, t: message.t } as ClientMessage;
    case 'chart.setSymbol':
      if (!isValidSymbol(message.symbol)) return null;
      return { v: message.v, t: 'chart.setSymbol', symbol: message.symbol };
    case 'chart.setTimeframe':
      if (!isValidTimeframe(message.timeframe)) return null;
      return { v: message.v, t: 'chart.setTimeframe', timeframe: message.timeframe };
    case 'drawing.create':
    case 'drawing.update': {
      if (!isValidDrawing(message.drawing)) return null;
      return { v: message.v, t: message.t, drawing: message.drawing };
    }
    case 'drawing.remove':
      if (!isValidDrawingId(message.id)) return null;
      return { v: message.v, t: 'drawing.remove', id: message.id };
    case 'voice.mute':
      if (typeof message.muted !== 'boolean') return null;
      return { v: message.v, t: 'voice.mute', muted: message.muted };
    case 'voice.speaking':
      if (typeof message.speaking !== 'boolean') return null;
      return { v: message.v, t: 'voice.speaking', speaking: message.speaking };
    default:
      return null;
  }
}

/** Clamps a raw frame to the protocol's size ceiling. */
export function isFrameWithinLimit(raw: string): boolean {
  return raw.length <= ROOM_MAX_FRAME_BYTES;
}

// ---------------------------------------------------------------------------
// Service-to-service subjects
// ---------------------------------------------------------------------------
//
// The API server and the Cloudflare Worker sign their internal calls with
// the same HMAC scheme. The SUBJECT is what the signature covers, so it must
// be built the same way on both sides. These helpers are the single
// definition of that format.

export function accessSubject(roomId: string, uid: string): string {
  return `${roomId}|${uid}`;
}

export function roomSubject(roomId: string): string {
  return roomId;
}

export function mediaSubject(key: string): string {
  return key;
}

/** The canonical service string that is signed. Keep in step with the API. */
export function canonicalServiceString(purpose: string, subject: string): string {
  return ["service", purpose, subject].join("|");
}
