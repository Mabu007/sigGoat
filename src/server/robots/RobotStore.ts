import fs from 'node:fs';
import path from 'node:path';
import type { Firestore } from 'firebase-admin/firestore';
import type { StrategyBacktestResult, StrategyLog, StrategyRuntimeState } from '../../services/strategy/engine';
import type { StrategyDefinition } from '../../services/strategy/schema';
import { getFirebaseAdmin } from '../firebaseAdmin';
import { firestoreSafe } from '../repositories';
import { assertStoreAvailable, ensureStoreDirectory, resolveStoreMode, type StoreModeDecision } from '../storeFs';
import { STARTER_ROBOTS, starterRobot } from './starterRobots';

export interface RobotRecord {
  id: string;
  slug: string;
  ownerUserId: string;
  creatorName: string;
  name: string;
  description: string;
  visibility: 'PUBLIC' | 'PRIVATE';
  currentVersionId: string;
  currentVersion: number;
  market: string;
  assetSelected?: boolean;
  timeframe: string;
  runtimeStatus: 'STOPPED' | 'PAPER' | 'ERROR';
  followerCount?: number;
  /**
   * The robot's cover image.
   *
   * The R2 OBJECT KEY plus its metadata, never a url: a signed delivery url
   * expires, so a stored url would be a broken image tomorrow. The url is
   * regenerated by the server on every read.
   */
  cover?: {
    key: string;
    contentType: string;
    size: number;
    updatedAt: string;
  };
  /**
   * The broker account this robot is bound to.
   *
   * A REFERENCE and nothing else. No token, no API key, no secret of any
   * kind is ever stored here — the credential stays in the encrypted vault
   * and the robot only remembers which of the owner's own authorized
   * accounts it should use.
   */
  brokerAccount?: {
    provider: 'ctrader' | 'propdao';
    /** The provider's own account id. */
    accountId: string;
    /** A human label, for the interface only. */
    label: string;
    /** The environment the account belongs to. */
    environment: 'demo' | 'live' | 'challenge' | 'funded' | 'unknown';
    updatedAt: string;
  };
  /**
   * The most recent verified backtest of this robot.
   *
   * A summary, not the full result: the directory needs to show whether a
   * robot has verified performance without reading every backtest.
   */
  lastBacktest?: {
    strategyVersionId: string;
    totalReturn: number;
    winRate: number;
    maxDrawdown: number;
    completedTrades: number;
    at: string;
  };
  alertPreferences?: { entry: boolean; exit: boolean; fill: boolean; risk: boolean };
  contactPhone?: string;
  telegram?: { chatId: string; username: string; updatedAt: string };
  createdAt: string;
  updatedAt: string;
}

export interface StoredBacktest {
  id: string;
  robotId: string;
  ownerUserId: string;
  strategyVersionId: string;
  configuration: { requestedBars: number; provider: string; instrument: string; timeframe: string; from?: string; to?: string };
  result: StrategyBacktestResult;
  createdAt: string;
}

interface RobotDb {
  robots: Record<string, RobotRecord>;
  versions: Record<string, StrategyDefinition>;
  runtime: Record<string, StrategyRuntimeState>;
  backtests: Record<string, StoredBacktest[]>;
  logs: Record<string, StrategyLog[]>;
}

const emptyDb = (): RobotDb => ({ robots: {}, versions: {}, runtime: {}, backtests: {}, logs: {} });
const safeId = (value: string) => value.replace(/[^A-Za-z0-9_-]/g, '_').slice(0, 180);

export class RobotStore {
  private readonly firestore?: Firestore;
  private readonly filePath: string;
  private decision: StoreModeDecision;
  private db: RobotDb = emptyDb();

  constructor(options: { firestore?: Firestore; filePath?: string } = {}) {
    this.firestore = options.firestore;
    this.filePath = options.filePath ?? path.join(process.env.DATA_DIR || path.join(process.cwd(), 'data'), 'robots.json');
    this.decision = resolveStoreMode(Boolean(this.firestore), 'RobotStore');
    if (!this.firestore && this.decision.mode !== 'unavailable') {
      this.decision = { ...this.decision, fileBacked: ensureStoreDirectory(this.filePath) };
      if (this.decision.fileBacked && fs.existsSync(this.filePath)) {
        try { this.db = { ...emptyDb(), ...JSON.parse(fs.readFileSync(this.filePath, 'utf8')) }; }
        catch (error) { console.warn('[robots] Saved robot data could not be read.', error); }
      }
    }
  }

  private assertAvailable() { assertStoreAvailable(this.decision, 'RobotStore'); }
  private persist() {
    if (!this.decision.fileBacked) return;
    try {
      const temporary = `${this.filePath}.tmp`;
      fs.writeFileSync(temporary, JSON.stringify(this.db), 'utf8');
      fs.renameSync(temporary, this.filePath);
    } catch (error) { this.decision = { ...this.decision, fileBacked: false }; console.warn('[robots] File persistence failed.', error); }
  }

  async create(robot: RobotRecord, definition: StrategyDefinition): Promise<void> {
    this.assertAvailable();
    const id = safeId(robot.id);
    if (this.firestore) {
      const ref = this.firestore.collection('robots').doc(id);
      await this.firestore.runTransaction(async transaction => {
        if ((await transaction.get(ref)).exists) throw new Error('ROBOT_ALREADY_EXISTS');
        transaction.create(ref, firestoreSafe({ ...robot, id }));
        transaction.create(ref.collection('versions').doc(safeId(definition.versionId)), firestoreSafe(definition));
      });
      return;
    }
    if (this.db.robots[id]) throw new Error('ROBOT_ALREADY_EXISTS');
    this.db.robots[id] = { ...robot, id };
    this.db.versions[definition.versionId] = definition;
    this.persist();
  }

  async get(idOrSlug: string): Promise<RobotRecord | null> {
    this.assertAvailable();
    if (this.firestore) {
      const byId = await this.firestore.collection('robots').doc(safeId(idOrSlug)).get();
      if (byId.exists) return byId.data() as RobotRecord;
      const bySlug = await this.firestore.collection('robots').where('slug', '==', idOrSlug).limit(1).get();
      return bySlug.empty ? (starterRobot(idOrSlug)?.robot ?? null) : bySlug.docs[0].data() as RobotRecord;
    }
    return this.db.robots[safeId(idOrSlug)] ?? Object.values(this.db.robots).find(robot => robot.slug === idOrSlug) ?? starterRobot(idOrSlug)?.robot ?? null;
  }

  async listPublic(limit = 60): Promise<RobotRecord[]> {
    this.assertAvailable();
    const robots = this.firestore
      ? (await this.firestore.collection('robots').where('visibility', '==', 'PUBLIC').limit(limit).get()).docs.map(doc => doc.data() as RobotRecord)
      : Object.values(this.db.robots).filter(robot => robot.visibility === 'PUBLIC');
    const ids = new Set(robots.map(robot => robot.id));
    const complete = [...robots, ...STARTER_ROBOTS.map(item => item.robot).filter(robot => !ids.has(robot.id))];
    return complete.sort((a, b) => b.updatedAt.localeCompare(a.updatedAt)).slice(0, limit);
  }

  async listForOwner(ownerUserId: string): Promise<RobotRecord[]> {
    this.assertAvailable();
    const robots = this.firestore
      ? (await this.firestore.collection('robots').where('ownerUserId', '==', ownerUserId).get()).docs.map(doc => doc.data() as RobotRecord)
      : Object.values(this.db.robots).filter(robot => robot.ownerUserId === ownerUserId);
    return robots.sort((a, b) => b.updatedAt.localeCompare(a.updatedAt));
  }

  async definition(robot: RobotRecord): Promise<StrategyDefinition | null> {
    const builtIn = starterRobot(robot.id);
    if (builtIn) return builtIn.definition;
    if (this.firestore) {
      const snapshot = await this.firestore.collection('robots').doc(robot.id).collection('versions').doc(safeId(robot.currentVersionId)).get();
      return snapshot.exists ? snapshot.data() as StrategyDefinition : null;
    }
    return this.db.versions[robot.currentVersionId] ?? null;
  }

  /** Selecting an asset creates a new immutable strategy version. */
  async setMarket(robot: RobotRecord, definition: StrategyDefinition): Promise<void> {
    this.assertAvailable();
    const updatedAt = new Date().toISOString();
    const changes = { currentVersionId: definition.versionId, currentVersion: definition.version, market: definition.market.instrument, timeframe: definition.market.timeframe, assetSelected: true, runtimeStatus: 'STOPPED' as const, lastBacktest: null, updatedAt };
    if (this.firestore) {
      const ref = this.firestore.collection('robots').doc(safeId(robot.id));
      await this.firestore.runTransaction(async transaction => {
        transaction.create(ref.collection('versions').doc(safeId(definition.versionId)), firestoreSafe(definition));
        transaction.set(ref, changes, { merge: true });
        transaction.delete(ref.collection('runtime').doc('current'));
      });
    } else {
      this.db.versions[definition.versionId] = definition;
      this.db.robots[robot.id] = { ...(this.db.robots[robot.id] ?? robot), ...changes, lastBacktest: undefined };
      delete this.db.runtime[robot.id];
      this.persist();
    }
  }

  async setAlertPreferences(robot: RobotRecord, alertPreferences: NonNullable<RobotRecord['alertPreferences']>): Promise<void> {
    this.assertAvailable();
    if (this.firestore) await this.firestore.collection('robots').doc(safeId(robot.id)).set({ alertPreferences }, { merge: true });
    else { this.db.robots[robot.id] = { ...(this.db.robots[robot.id] ?? robot), alertPreferences }; this.persist(); }
  }

  async setContactPhone(robot: RobotRecord, contactPhone: string): Promise<void> {
    this.assertAvailable();
    if (this.firestore) await this.firestore.collection('robots').doc(safeId(robot.id)).set({ contactPhone }, { merge: true });
    else { this.db.robots[robot.id] = { ...(this.db.robots[robot.id] ?? robot), contactPhone }; this.persist(); }
  }

  async setTelegram(robot: RobotRecord, telegram: RobotRecord['telegram'] | null): Promise<void> {
    this.assertAvailable();
    if (this.firestore) await this.firestore.collection('robots').doc(safeId(robot.id)).set({ telegram: telegram ?? null }, { merge: true });
    else { this.db.robots[robot.id] = { ...(this.db.robots[robot.id] ?? robot), telegram: telegram ?? undefined }; this.persist(); }
  }

  async setRuntime(robot: RobotRecord, state: StrategyRuntimeState): Promise<void> {
    this.assertAvailable();
    const updatedAt = new Date().toISOString();
    if (this.firestore) {
      const ref = this.firestore.collection('robots').doc(robot.id);
      const batch = this.firestore.batch();
      batch.set(ref.collection('runtime').doc('current'), firestoreSafe({ ...state, ownerUserId: robot.ownerUserId, updatedAt }));
      batch.set(ref, { runtimeStatus: state.status, updatedAt }, { merge: true });
      await batch.commit();
    } else {
      this.db.runtime[robot.id] = state;
      this.db.robots[robot.id] = { ...(this.db.robots[robot.id] ?? robot), runtimeStatus: state.status, updatedAt };
      this.persist();
    }
  }

  async runtime(robot: RobotRecord): Promise<StrategyRuntimeState | null> {
    if (this.firestore) {
      const snapshot = await this.firestore.collection('robots').doc(robot.id).collection('runtime').doc('current').get();
      return snapshot.exists ? snapshot.data() as StrategyRuntimeState : null;
    }
    return this.db.runtime[robot.id] ?? null;
  }

  async appendLogs(robot: RobotRecord, entries: StrategyLog[]): Promise<void> {
    if (!entries.length) return;
    if (this.firestore) {
      const batch = this.firestore.batch();
      for (const entry of entries.slice(-100)) batch.set(this.firestore.collection('robots').doc(robot.id).collection('logs').doc(safeId(entry.id)), firestoreSafe({ ...entry, ownerUserId: robot.ownerUserId }));
      await batch.commit();
    } else { this.db.logs[robot.id] = [...(this.db.logs[robot.id] ?? []), ...entries].slice(-500); this.persist(); }
  }

  async listLogs(robot: RobotRecord, limit = 100): Promise<StrategyLog[]> {
    if (this.firestore) {
      const snapshot = await this.firestore.collection('robots').doc(robot.id).collection('logs').orderBy('at', 'desc').limit(limit).get();
      return snapshot.docs.map(doc => doc.data() as StrategyLog).reverse();
    }
    return (this.db.logs[robot.id] ?? []).slice(-limit);
  }

  async saveBacktest(record: StoredBacktest): Promise<void> {
    if (this.firestore) await this.firestore.collection('robots').doc(record.robotId).collection('backtests').doc(safeId(record.id)).set(firestoreSafe(record));
    else { this.db.backtests[record.robotId] = [record, ...(this.db.backtests[record.robotId] ?? [])].slice(0, 20); this.persist(); }
  }

  async listBacktests(robot: RobotRecord, limit = 10): Promise<StoredBacktest[]> {
    if (this.firestore) {
      const snapshot = await this.firestore.collection('robots').doc(robot.id).collection('backtests').orderBy('createdAt', 'desc').limit(limit).get();
      return snapshot.docs.map(doc => doc.data() as StoredBacktest);
    }
    return (this.db.backtests[robot.id] ?? []).slice(0, limit);
  }

  // -- the mutable extras ------------------------------------------------

  /**
   * Saves the robot's cover.
   *
   * Only the owner may call this, and the CALLER enforces that: the store
   * holds no notion of a session.
   */
  async setCover(robot: RobotRecord, cover: RobotRecord['cover']): Promise<void> {
    this.assertAvailable();
    const id = safeId(robot.id);
    const updatedAt = new Date().toISOString();
    if (this.firestore) {
      await this.firestore.collection('robots').doc(id).set(firestoreSafe({ cover: cover ?? null, updatedAt }), { merge: true });
      return;
    }
    this.db.robots[id] = { ...(this.db.robots[id] ?? robot), cover, updatedAt };
    this.persist();
  }

  /** Clears the robot's cover, which restores the designed default artwork. */
  async clearCover(robot: RobotRecord): Promise<void> {
    await this.setCover(robot, undefined);
  }

  /**
   * Binds the robot to one of the owner's own broker accounts.
   *
   * The stored value is a REFERENCE. The credential never leaves the
   * encrypted vault.
   */
  async setBrokerAccount(robot: RobotRecord, account: RobotRecord['brokerAccount']): Promise<void> {
    this.assertAvailable();
    const id = safeId(robot.id);
    const updatedAt = new Date().toISOString();
    if (this.firestore) {
      await this.firestore.collection('robots').doc(id).set(firestoreSafe({ brokerAccount: account ?? null, updatedAt }), { merge: true });
      return;
    }
    this.db.robots[id] = { ...(this.db.robots[id] ?? robot), brokerAccount: account, updatedAt };
    this.persist();
  }

  /** Records the most recent verified backtest summary on the robot. */
  async setLastBacktest(robot: RobotRecord, summary: RobotRecord['lastBacktest']): Promise<void> {
    this.assertAvailable();
    const id = safeId(robot.id);
    const updatedAt = new Date().toISOString();
    if (this.firestore) {
      await this.firestore.collection('robots').doc(id).set(firestoreSafe({ lastBacktest: summary ?? null, updatedAt }), { merge: true });
      return;
    }
    this.db.robots[id] = { ...(this.db.robots[id] ?? robot), lastBacktest: summary, updatedAt };
    this.persist();
  }

}

let shared: RobotStore | undefined;
export function createRobotStore(): RobotStore {
  return shared ??= new RobotStore({ firestore: getFirebaseAdmin()?.firestore });
}
