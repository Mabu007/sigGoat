/**
 * The primary security/runtime boundary for model output.
 *
 * UNKNOWN JSON enters here.
 *
 * Only a fully validated ReasoningResult leaves here.
 *
 * Throws:
 *   ReasoningValidationError
 *
 * Never allow raw parsed model JSON to bypass this function.
 */
export function parseReasoningResult(
  raw: unknown,
): ReasoningResult {
  const issues: string[] = [];

  if (!isPlainObject(raw)) {
    throw new ReasoningValidationError([
      'response must be a JSON object',
    ]);
  }

  const investigation =
    parseInvestigation(
      raw.investigation,
      issues,
    );

  /*
   * Proposal market is only a fallback for evidence.
   *
   * The runtime market is authoritative and will be checked later
   * by SignalGate.
   */
  const marketFromProposal =
    isPlainObject(raw.proposal) &&
    typeof raw.proposal.market === 'string'
      ? raw.proposal.market.trim()
      : undefined;

  const evidence =
    parseEvidenceList(
      raw.evidence,
      marketFromProposal || 'unknown',
      issues,
    );

  const thesis =
    parseThesis(
      raw.thesis,
      issues,
    );

  const proposal =
    parseProposal(
      raw.proposal,
      issues,
    );

  if (
    issues.length > 0 ||
    !investigation ||
    !thesis ||
    !proposal
  ) {
    throw new ReasoningValidationError(
      issues.length > 0
        ? issues
        : [
            'response is missing required sections',
          ],
    );
  }

  return {
    investigation,
    thesis,
    proposal,
    evidence,
  };
}

