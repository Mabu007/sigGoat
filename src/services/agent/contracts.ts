export interface EvidenceItem {
  /**
   * Stable identifier generated by the parser.
   *
   * The model does not control this value.
   */
  id: string;

  /**
   * What produced the observation.
   *
   * Examples:
   *   RSI_14
   *   EMA_CROSS
   *   STRUCTURE
   *   LLM_PATTERN
   */
  source: string;

  market: string;

  timeframe?: string;

  /**
   * Human-readable observation.
   *
   * This is an interpretation supplied by the model and must not be
   * treated as independently verified market data.
   */
  observation: string;

  bias?: MarketBias;

  classification: EvidenceClassification;

  /**
   * Optional model timestamp.
   *
   * Runtime timestamps remain authoritative elsewhere.
   */
  timestamp?: number;
}

export interface TrackerDirective {
  description: string;
  type: TrackerConditionType;

  /**
   * Indicator expression.
   *
   * A tracker is "an indicator being in a certain value" — e.g.
   *   { indicator: 'EMA', period: 20 } CROSS_ABOVE targetValue: 1.2345
   *   { indicator: 'RSI', period: 14 } CROSS_BELOW targetValue: 30
   *
   * The runtime recomputes the value from candles and compares it to
   * targetValue. A tracker with an indicator and a targetValue is therefore
   * fully deterministic and never depends on the model at evaluation time.
   */
  indicator?: IndicatorType;
  period?: number;
  fastPeriod?: number;
  slowPeriod?: number;
  session?: 'LONDON' | 'NEW_YORK' | 'ASIAN';

  targetValue?: number;
  operator?: TrackerOperator;
}

export interface ReasoningInvestigation {
  summary: string;
  marketView?: string;
}

export interface ReasoningThesis {
  directionalBias: MarketBias;
  summary: string;
  confidence: number;
  invalidation?: string;
  observationPlan?: string;
  trackers: TrackerDirective[];
}

export interface TradeProposal {
  decision: ReasoningDecision;

  direction?: TradeDirection;
  orderType?: OrderType;

  /**
   * Optional because the runtime already knows which market is being
   * evaluated. If supplied by the model, SignalGate must verify it.
   */
  market?: string;

  entry?: number;

  entryZone?: {
    low: number;
    high: number;
  } | null;

  stopLoss?: number;
  takeProfit?: number;

  /**
   * THE CONDITIONAL TRADE IDEA.
   *
   * An ordered chain of wait-for conditions, e.g.
   *   1. "EMA(20) crosses above 1.2345"
   *   2. "price holds above 1.2340 for one 1h close"
   *   3. "then consider LONG from the 1.2340-1.2360 zone"
   *
   * A signal is NEVER "buy now". Every actionable proposal must describe the
   * conditions that must be satisfied FIRST. Each entry is additionally
   * materialised as a deterministic Tracker so the platform can alert the
   * user when a condition is actually met.
   */
  triggerSequence?: string[];

  /**
   * Model-calculated RR is informational only.
   *
   * SignalGate must calculate authoritative RR from entry/SL/TP.
   */
  riskReward?: number;

  /**
   * Proposal confidence is informational. Thesis confidence is the
   * canonical confidence used by the current runtime gate.
   */
  confidence?: number;

  rationale?: string;
  confirmationRequired?: string;
  invalidation?: string;
  noTradeReason?: string;
}

export interface ReasoningResult {
  investigation: ReasoningInvestigation;
  thesis: ReasoningThesis;
  proposal: TradeProposal;
  evidence: EvidenceItem[];
}

