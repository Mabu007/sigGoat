/**
 * Small deterministic string hash.
 *
 * Used only for stable evidence identifiers.
 * It is NOT a cryptographic hash.
 */
export function hashString(
  value: string,
): number {
  let hash = 0;

  for (
    let i = 0;
    i < value.length;
    i++
  ) {
    hash =
      (hash << 5) -
      hash +
      value.charCodeAt(i);

    hash |= 0;
  }

  return hash;
}

/**
 * Deterministic seeded PRNG (mulberry32).
 *
 * Useful for PAPER/backtest simulations where reproducibility matters.
 */
export function seededRandom(
  seed: number,
): () => number {
  let a = seed >>> 0;

  return () => {
    a |= 0;
    a =
      (a + 0x6d2b79f5) |
      0;

    let t =
      Math.imul(
        a ^ (a >>> 15),
        1 | a,
      );

    t =
      (t +
        Math.imul(
          t ^ (t >>> 7),
          61 | t,
        )) ^
      t;

    return (
      ((t ^ (t >>> 14)) >>> 0) /
      4294967296
    );
  };
}

/**
 * Sanitize error messages before they reach UI/API responses.
 */
export function sanitizeErrorMessage(
  message: string,
): string {
  return message
    .replace(
      /sk-or-v1-[a-zA-Z0-9_-]+/g,
      '[REDACTED_API_KEY]',
    )
    .replace(
      /Bearer\s+[^\s]+/gi,
      'Bearer [REDACTED]',
    )
    .replace(
      /bot\d+:[A-Za-z0-9_-]+/g,
      '[REDACTED_BOT_TOKEN]',
    )
    .slice(0, 500);
}