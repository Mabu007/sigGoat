/* Validation error                                                   */
/* ------------------------------------------------------------------ */

export class ReasoningValidationError extends Error {
  readonly issues: string[];

  constructor(issues: string[]) {
    super(
      `Reasoning result failed validation: ${issues.join('; ')}`,
    );

    this.name = 'ReasoningValidationError';
    this.issues = issues;
  }
}

