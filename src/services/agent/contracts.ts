/**
 * CANONICAL REASONING CONTRACT
 * =============================
 *
 * This is the single runtime boundary between untrusted LLM output and
 * SignalGOAT business logic.
 *
 * Pipeline:
 *
 *   LLM JSON
 *      ↓
 *   parseReasoningResult()
 *      ↓
 *   validated ReasoningResult
 *      ↓
 *   GoatDurableObject
 *      ↓
 *   SignalGate
 *
 * IMPORTANT:
 * - Never pass raw LLM JSON into business logic.
 * - Never trust model-calculated risk/reward.
 * - Never trust model output as market-data truth.
 * - Deterministic runtime validation remains authoritative.
 *
 * Concept separation:
 *   direction  = LONG | SHORT
 *   orderType  = LIMIT | STOP | MARKET
 *   bias       = BULLISH | BEARISH | NEUTRAL
 *   decision   = ACTIONABLE | NO_TRADE
 */

